FIELD_LABELS = LABELS['fr']['fields']
OPTION_LABELS = LABELS['fr']['options']


def _current():
    return LABELS.get((translation.get_language() or 'fr')[:2], LABELS['fr'])


def field_label(key):
    """Libellé d'un champ dans la langue de la page (ex. « father_name » → « Nom du père »)."""
    return _current()['fields'].get(key) or FIELD_LABELS.get(key) or key.replace('_', ' ').capitalize()


def option_label(value):
    """Libellé d'une valeur de liste dans la langue de la page (ex. « taxi » → « Taxi »)."""
    return _current()['options'].get(value) or OPTION_LABELS.get(value) or value
